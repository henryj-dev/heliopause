// Keep the shared key union permissive for callers while the actual classic
// table above controls what the fallback serialises to the browser.
export type MessageKey = keyof typeof SHARED_MESSAGES;

export function t(lang: Lang, key: MessageKey, params: Record<string, string | number> = {}): string {
  const entry = MESSAGES[key as keyof typeof MESSAGES];
  const raw = entry ? (lang === "en" ? entry.en : entry.ko ?? entry.en) : key;
  return raw.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
  );
}
