export function crumbLabel(lang: Lang, crumb: string): string {
  const key = CRUMB_KEYS[crumb];
  return key ? t(lang, key) : crumb;
}

export function t(lang: Lang, key: MessageKey, params: Record<string, string | number> = {}): string {
  const entry = MESSAGES[key] as { en: string; ko?: string };
  const raw = (lang === "en" ? entry.en : entry.ko ?? entry.en) ?? key;
  return raw.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
  );
}

