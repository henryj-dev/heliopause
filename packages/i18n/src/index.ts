export function pickLang(input: { override?: string | null; acceptLanguage?: string | null }): Lang {
  const wanted = (input.override ?? "").toLowerCase();
  if (LANGS.includes(wanted as Lang)) return wanted as Lang;
  for (const part of (input.acceptLanguage ?? "").split(",")) {
    const tag = part.split(";")[0]?.trim().toLowerCase() ?? "";
    const primary = tag.split("-")[0];
    if (primary && LANGS.includes(primary as Lang)) return primary as Lang;
  }
  return "en";
}
